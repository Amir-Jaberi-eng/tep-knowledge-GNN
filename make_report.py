"""
make_report.py -- turn results/results.json into tables, a figure and a graph analysis.

    python make_report.py

Writes
  results/results_table.md    mean ± std over seeds for every experiment
  results/scores.png          every seed and the mean ± std, per experiment
  results/graph_analysis.md   how the graphs differ (edges, correlations, smoothing)
  docs/knowledge_graph.md     the process-knowledge graph, edge by edge
and replaces the block between <!-- RESULTS:START --> and <!-- RESULTS:END --> in README.md.
"""
import json
import os
import re

import numpy as np

import tep_utils as U

RESULTS = "results/results.json"
BUDGET_TAG = "/class"


def display(name):
    """Readable label: 'R-GCN+res | knowledge (typed) | 30/class' -> 'R-GCN + residual · knowledge (typed)'."""
    parts = [p for p in name.split(" | ") if not p.endswith(BUDGET_TAG)]
    return " · ".join(parts).replace("+res", " + residual")


def summary(results):
    names = list(dict.fromkeys(v["name"] for v in results.values()))
    rows = []
    for n in names:
        r = [v for v in results.values() if v["name"] == n]
        f = np.array([v["f1"] for v in r])
        g = np.array([v["f1_no_hard"] for v in r])
        rows.append({"name": n, "n": len(r), "f1": f, "mean": f.mean(), "std": f.std(),
                     "mean_nh": g.mean(), "std_nh": g.std(), "budget": BUDGET_TAG in n})
    return rows


def table_md(rows, title):
    lines = [f"**{title}**", "",
             "| Model and graph | Seeds | Macro-F1, 22 classes | Macro-F1 without faults 3, 9, 15 |",
             "|---|---|---|---|"]
    for r in rows:
        lines.append(f"| {display(r['name'])} | {r['n']} | {r['mean']:.3f} ± {r['std']:.3f} "
                     f"| {r['mean_nh']:.3f} ± {r['std_nh']:.3f} |")
    return "\n".join(lines)


def figure(rows, path):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    groups = [("All training windows", [r for r in rows if not r["budget"]]),
              ("30 training windows per class", [r for r in rows if r["budget"]])]
    groups = [(t, g) for t, g in groups if g]
    n = sum(len(g) for _, g in groups)
    fig, axes = plt.subplots(len(groups), 1, figsize=(9, 0.32 * n + 1.6 * len(groups)),
                             gridspec_kw={"height_ratios": [len(g) for _, g in groups]}, squeeze=False)
    for ax, (title, g) in zip(axes[:, 0], groups):
        y = np.arange(len(g))[::-1]
        no_edge = [r["mean"] for r in g if "empty" in r["name"]]
        if no_edge:
            ax.axvline(max(no_edge), color="0.4", ls="--", lw=1, label="best model without edges")
        for yi, r in zip(y, g):
            c = "#1f6fd1" if "(typed)" in r["name"] else "0.45"
            ax.plot([r["mean"] - r["std"], r["mean"] + r["std"]], [yi, yi], color=c, lw=2)
            ax.plot([r["mean"]], [yi], marker="|", ms=12, mew=2.5, color=c)
            ax.scatter(r["f1"], [yi] * len(r["f1"]), s=10, color=c, alpha=0.55, zorder=3)
            ax.text(0.715, yi, f"{r['mean']:.3f} ± {r['std']:.3f}", va="center", fontsize=8,
                    color="black" if "(typed)" in r["name"] else "0.35")
        ax.set_yticks(y)
        ax.set_yticklabels([display(r["name"]) for r in g], fontsize=8.5)
        ax.set_xlim(0.40, 0.70)
        ax.set_title(title, loc="left", fontsize=10, fontweight="bold")
        ax.grid(axis="x", color="0.9")
        ax.spines[["top", "right"]].set_visible(False)
        ax.legend(loc="lower left", fontsize=8, frameon=False)
    axes[-1, 0].set_xlabel("test macro-F1, 22 classes (dots: seeds; bar: mean ± std)")
    fig.tight_layout()
    fig.savefig(path, dpi=160)
    plt.close(fig)


def graph_analysis(path):
    """Edges per type, overlap with the correlation graph, and how much two GCN layers smooth."""
    train, test = U.load_tep(U.download_tep("tep_data"))
    (X_train, y_train), _, _ = U.build_datasets(train, test, window=20)
    X_train = U.Standardizer().fit(X_train).transform(X_train)
    n_edges = U.structure_graph().shape[1] // 2
    graphs = {"knowledge": U.structure_graph(),
              "correlation": U.correlation_graph(X_train[y_train == 0], n_edges),
              "random": U.random_graph(n_edges, seed=0), "empty": U.empty_graph()}
    as_set = lambda ei: {tuple(sorted(p)) for p in ei.T.tolist()}
    C = np.abs(np.corrcoef(X_train[y_train == 0].reshape(-1, U.N_VARS).T))
    iu = np.triu_indices(U.N_VARS, k=1)
    K, R = as_set(graphs["knowledge"]), as_set(graphs["correlation"])

    def gcn_matrix(ei, n=U.N_VARS):
        A = np.zeros((n, n)); A[ei[0], ei[1]] = 1; A += np.eye(n)
        d = 1 / np.sqrt(A.sum(axis=1))
        return d[:, None] * A * d[None, :]

    out = ["# Graph analysis", "",
           "Generated by `make_report.py` from the training data (normal operation for correlations).", "",
           "## Knowledge edges by type", "",
           "| Edge type | Edges | Median \\|r\\| in normal data | Also in the correlation graph |",
           "|---|---|---|---|"]
    for t in U.EDGE_TYPES:
        E = as_set(U.structure_graph((t,)))
        out.append(f"| {t} | {len(E)} | {np.median([C[a, b] for a, b in E]):.2f} | {len(E & R)} |")
    out += ["", f"Distinct knowledge edges: {len(K)}. Shared with the correlation graph: {len(K & R)}. "
                f"Median \\|r\\| over all variable pairs: {np.median(C[iu]):.2f}.", "",
            "Strongest correlations that are not knowledge edges:", ""]
    for a, b in sorted(R - K, key=lambda p: -C[p])[:5]:
        out.append(f"- `{U.VAR_NAMES[a]}` ({U.VAR_DESCRIPTIONS[U.VAR_NAMES[a]]}) – `{U.VAR_NAMES[b]}` "
                   f"({U.VAR_DESCRIPTIONS[U.VAR_NAMES[b]]}): \\|r\\| = {C[a, b]:.2f}")
    out += ["", "## What two GCN layers do to the 52 sensors", "",
            "For each graph, the rows of Â² (two GCN layers without weights) say which inputs each sensor "
            "ends up mixing. A sensor has a near-duplicate if another sensor's mixture has cosine "
            "similarity above 0.95; the effective rank (exp of the entropy of the normalised singular "
            "values) counts how many distinct mixtures remain (52 = all distinct).", "",
            "| Graph | Edges | Isolated sensors | Sensors with a near-duplicate | Effective number of distinct mixtures |",
            "|---|---|---|---|---|"]
    for name, ei in graphs.items():
        deg = np.bincount(ei[0], minlength=U.N_VARS) if ei.shape[1] else np.zeros(U.N_VARS)
        M = gcn_matrix(ei) @ gcn_matrix(ei)
        Rn = M / np.linalg.norm(M, axis=1, keepdims=True)
        sim = Rn @ Rn.T; np.fill_diagonal(sim, 0)
        sv = np.linalg.svd(M, compute_uv=False); p = sv / sv.sum()
        eff = np.exp(-(p * np.log(p + 1e-12)).sum())
        out.append(f"| {name} | {ei.shape[1] // 2} | {int((deg == 0).sum())} | "
                   f"{int((sim.max(axis=1) > 0.95).sum())} | {eff:.1f} |")
    loops = U.extract_control_loops(os.path.join(U.download_tep("tep_data"), "temain_mod.f"))
    missing = sorted(set(U.CONTROL_LINKS) - set(loops.values()))
    out += ["", "## Control loops: code versus hand-written list", "",
            f"`extract_control_loops` reads {len(loops)} loops from `temain_mod.f`; all of them are in "
            f"`CONTROL_LINKS`. The hand-written list has {len(missing)} more: "
            + ", ".join(f"`{a}`–`{b}`" for a, b in missing)
            + " (the override in `CONTRL6` that opens the purge valve on high separator pressure).", ""]
    with open(path, "w") as f:
        f.write("\n".join(out) + "\n")


def knowledge_doc(path):
    loops = U.extract_control_loops(os.path.join(U.download_tep("tep_data"), "temain_mod.f"))
    routine = {pair: f"CONTRL{n}" for n, pair in loops.items()}
    d = U.VAR_DESCRIPTIONS
    out = ["# The process-knowledge graph", "",
           "Generated by `make_report.py` from `tep_utils.py` (UNITS, STREAM_LINKS, CONTROL_LINKS). "
           "Edit those lists, not this file.", "",
           "## Units (every pair inside a unit is connected)", "",
           "| Unit | Variables |", "|---|---|"]
    for unit, members in U.UNITS.items():
        out.append(f"| {unit} | " + ", ".join(f"`{m}` {d[m]}" for m in members) + " |")
    out += ["", "## Stream links", "", "| From | To |", "|---|---|"]
    for a, b in U.STREAM_LINKS:
        out.append(f"| `{a}` {d[a]} | `{b}` {d[b]} |")
    out += ["", "## Control links (measurement watched, valve finally moved)", "",
            "| Measurement | Valve | Source in temain_mod.f |", "|---|---|---|"]
    for a, b in U.CONTROL_LINKS:
        out.append(f"| `{a}` {d[a]} | `{b}` {d[b]} | {routine.get((a, b), 'CONTRL6 override (IF statements)')} |")
    with open(path, "w") as f:
        f.write("\n".join(out) + "\n")


def main():
    results = json.load(open(RESULTS))
    rows = summary(results)
    full = [r for r in rows if not r["budget"]]
    small = [r for r in rows if r["budget"]]
    tables = table_md(full, "All training windows (about 365 per fault)")
    if small:
        tables += "\n\n" + table_md(small, "30 training windows per class")
    with open("results/results_table.md", "w") as f:
        f.write(tables + "\n")
    figure(rows, "results/scores.png")
    graph_analysis("results/graph_analysis.md")
    os.makedirs("docs", exist_ok=True)
    knowledge_doc("docs/knowledge_graph.md")
    if os.path.exists("README.md"):
        readme = open("README.md").read()
        new = re.sub(r"<!-- RESULTS:START -->.*<!-- RESULTS:END -->",
                     lambda m: "<!-- RESULTS:START -->\n" + tables + "\n<!-- RESULTS:END -->",
                     readme, flags=re.S)
        with open("README.md", "w") as f:
            f.write(new)
    print("Wrote results/results_table.md, results/scores.png, results/graph_analysis.md, "
          "docs/knowledge_graph.md and updated README.md")


if __name__ == "__main__":
    main()
